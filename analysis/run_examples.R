# Все примеры вывода R, показанные на сайте. Запускать из папки data/.
options(width = 70)
suppressPackageStartupMessages({library(survival); library(pROC); library(pwr); library(psych); library(lmerTest); library(tidyr)})
sec <- function(x) cat("\n#####", x, "#####\n")
trial <- read.csv("trial.csv", stringsAsFactors = TRUE)
trial$arm <- factor(trial$arm, levels = c("placebo", "dose10", "dose20"))
trial$change <- trial$hamd_8 - trial$hamd_0
screening <- read.csv("screening.csv"); raters <- read.csv("raters.csv")

sec("str"); str(trial)
sec("summary_hamd0"); summary(trial$hamd_0)
sec("sd"); sd(trial$hamd_0)
sec("by_arm"); aggregate(hamd_0 ~ arm, data = trial, FUN = function(x) c(mean = mean(x), sd = sd(x)))
sec("table_sex"); table(trial$sex, trial$arm)
sec("relapse_week_summary"); summary(trial$relapse_week)
sec("shapiro"); shapiro.test(trial$hamd_0)
sec("shapiro_change"); shapiro.test(trial$change)
two <- droplevels(subset(trial, arm != "dose10"))
sec("ttest"); t.test(change ~ arm, data = two)
sec("wilcox"); wilcox.test(change ~ arm, data = two)
sec("paired"); with(subset(trial, arm == "dose20"), t.test(hamd_8, hamd_0, paired = TRUE))
sec("cohend"); m <- tapply(two$change, two$arm, mean); s <- tapply(two$change, two$arm, sd); print((m[2]-m[1])/sqrt((s[1]^2+s[2]^2)/2))
sec("aov"); fit <- aov(change ~ arm, data = trial); summary(fit)
sec("tukey"); TukeyHSD(fit)
sec("kruskal"); kruskal.test(change ~ arm, data = trial)
sec("padjust"); p.adjust(c(0.012, 0.030, 0.041, 0.20), method = "holm")
sec("tab_resp"); tab <- table(trial$arm, trial$response); tab
sec("chisq"); chisq.test(tab)
sec("tab_nausea"); tn <- table(two$arm, two$rash); tn
sec("fisher"); fisher.test(tn)
sec("chisq_expected"); chisq.test(tn)$expected
sec("cor_p"); cor.test(trial$phq9_0, trial$hamd_0)
sec("cor_s"); cor.test(trial$phq9_0, trial$hamd_0, method = "spearman", exact = FALSE)
sec("lm"); m1 <- lm(hamd_8 ~ arm + hamd_0 + age + sex, data = trial); summary(m1)
sec("lm_ci"); confint(m1)
sec("glm"); g1 <- glm(response ~ arm + hamd_0 + sex, data = trial, family = binomial); summary(g1)
sec("glm_or"); round(exp(cbind(OR = coef(g1), confint(g1))), 2)
sec("diag_tab"); screening$pos <- factor(ifelse(screening$phq9 >= 10, "PHQ>=10", "PHQ<10"), levels = c("PHQ>=10","PHQ<10")); screening$dx <- factor(ifelse(screening$mdd==1,"MDD_yes","MDD_no"), levels=c("MDD_yes","MDD_no")); table(screening$pos, screening$dx)
sec("roc"); r <- roc(screening$mdd, screening$phq9, quiet = TRUE); print(auc(r)); print(ci.auc(r))
sec("coords"); coords(r, "best", ret = c("threshold", "sensitivity", "specificity"))
sec("km"); km <- survfit(Surv(relapse_week, relapse) ~ arm, data = trial); km
sec("km_sum"); summary(km, times = c(26, 52))
sec("logrank"); survdiff(Surv(relapse_week, relapse) ~ arm, data = trial)
sec("cox"); cx <- coxph(Surv(relapse_week, relapse) ~ arm + age, data = trial); summary(cx)
sec("zph"); cox.zph(cx)
sec("alpha"); alpha(screening[, paste0("phq_", 1:9)])$total
sec("icc"); ICC(raters[, c("hamd_r1", "hamd_r2")])
sec("kappa"); cohen.kappa(table(raters$dx_r1, raters$dx_r2))
sec("lmer"); long <- pivot_longer(trial, cols = c(hamd_0, hamd_2, hamd_4, hamd_8), names_to = "week", names_prefix = "hamd_", values_to = "hamd"); long$week <- as.numeric(long$week)
mm <- lmer(hamd ~ week * arm + (1 | id), data = long); summary(mm)
sec("anova_mm"); anova(mm)
sec("pwr"); pwr.t.test(d = 0.5, power = 0.80, sig.level = 0.05)
sec("powert"); power.t.test(delta = 3, sd = 6, power = 0.80)
sec("powerprop"); power.prop.test(p1 = 0.30, p2 = 0.50, power = 0.80)
